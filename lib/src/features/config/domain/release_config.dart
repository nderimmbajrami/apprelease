import '../../apps/domain/app_project.dart';
import '../../credentials/domain/credential.dart';

/// Generates `apprelease.yaml` for an app from its settings and the
/// credentials the team has added. Pure Dart; the output is what the docs
/// describe, so the runner and the file never disagree.
class ReleaseConfig {
  const ReleaseConfig({required this.app, this.credentials = const []});

  final AppProject app;
  final List<Credential> credentials;

  /// The app's own credential of that kind, else a shared one, else any.
  Credential? _first(CredentialKind kind) {
    Credential? shared, other;
    for (final c in credentials) {
      if (c.kind != kind) continue;
      if (c.appId == app.id) return c;
      if (c.appId == null) {
        shared ??= c;
      } else {
        other ??= c;
      }
    }
    return shared ?? other;
  }

  bool get hasKeystore => _first(CredentialKind.androidKeystore) != null;
  bool get hasGooglePlay =>
      _first(CredentialKind.googlePlayServiceAccount) != null;
  bool get hasAppStoreConnect =>
      _first(CredentialKind.appStoreConnectKey) != null;

  /// Whether every section the app's platforms need can be filled in.
  bool get isComplete =>
      (!app.hasAndroid || (hasKeystore && hasGooglePlay)) &&
      (!app.hasIos || hasAppStoreConnect);

  String toYaml() {
    final out = StringBuffer()
      ..writeln('# Generated by AppRelease for ${app.name}.')
      ..writeln('# Commit this file as apprelease.yaml in the repository root.')
      ..writeln('workflows:');
    if (app.hasAndroid) out.write(_android());
    if (app.hasIos) out.write(_ios());
    return out.toString();
  }

  String _android() {
    final keystore = _first(CredentialKind.androidKeystore);
    final play = _first(CredentialKind.googlePlayServiceAccount);
    final b = StringBuffer()
      ..writeln('  android-production:')
      ..writeln('    name: ${app.name} · Android')
      ..writeln('    max_build_duration: 60')
      ..writeln('    instance_type: linux_x2')
      ..writeln('    environment:')
      ..writeln('      flutter: ${app.flutterVersion}')
      ..writeln('      java: 17');
    if (keystore != null) {
      b
        ..writeln('      android_signing:')
        ..writeln('        - ${keystore.name}');
    } else {
      b.writeln(
        '      # android_signing: add an Android keystore under Credentials',
      );
    }
    if (play != null) {
      b
        ..writeln('      groups:')
        ..writeln('        - ${play.name}');
    }
    b
      ..writeln('      vars:')
      ..writeln('        PACKAGE_NAME: "${app.androidPackageName}"');
    if (play != null) {
      b
        ..writeln('    versioning:')
        ..writeln('      source: google_play');
    }
    b
      ..writeln('    scripts:')
      ..writeln('      - name: Get packages')
      ..writeln('        script: flutter pub get')
      ..writeln('      - name: Build app bundle')
      ..writeln('        script: |')
      ..writeln('          flutter build appbundle --release \\')
      ..writeln('            --build-number=\$AR_BUILD_NUMBER')
      ..writeln('    artifacts:')
      ..writeln('      - build/**/outputs/**/*.aab')
      ..writeln('      - build/**/outputs/**/mapping.txt')
      ..writeln('    publishing:');
    if (play != null) {
      b
        ..writeln('      google_play:')
        ..writeln('        credentials: \$GOOGLE_PLAY_SERVICE_ACCOUNT')
        ..writeln('        track: internal')
        ..writeln('        submit_as_draft: false');
    } else {
      b.writeln(
        '      # google_play: add a Google Play service account under Credentials',
      );
    }
    b
      ..writeln('      email:')
      ..writeln('        recipients:')
      ..writeln('          - team@example.com')
      ..writeln();
    return b.toString();
  }

  String _ios() {
    final asc = _first(CredentialKind.appStoreConnectKey);
    final b = StringBuffer()
      ..writeln('  ios-testflight:')
      ..writeln('    name: ${app.name} · iOS')
      ..writeln('    max_build_duration: 90')
      ..writeln('    instance_type: mac_m2')
      ..writeln('    environment:')
      ..writeln('      flutter: ${app.flutterVersion}')
      ..writeln('      xcode: latest');
    if (asc != null) {
      b
        ..writeln('      ios_signing:')
        ..writeln('        distribution_type: app_store')
        ..writeln('        bundle_identifier: ${app.iosBundleId}')
        ..writeln('    versioning:')
        ..writeln('      source: app_store_connect');
    } else {
      b.writeln(
        '      # ios_signing: add an App Store Connect API key under Credentials',
      );
    }
    b
      ..writeln('    scripts:')
      ..writeln('      - name: Get packages')
      ..writeln('        script: flutter pub get')
      ..writeln('      - name: Install CocoaPods dependencies')
      ..writeln('        script: cd ios && pod install')
      ..writeln('      - name: Build ipa')
      ..writeln('        script: |')
      ..writeln('          flutter build ipa --release \\')
      ..writeln('            --build-number=\$AR_BUILD_NUMBER \\')
      ..writeln('            --export-options-plist=\$AR_EXPORT_OPTIONS')
      ..writeln('    artifacts:')
      ..writeln('      - build/ios/ipa/*.ipa')
      ..writeln('    publishing:');
    if (asc != null) {
      b
        ..writeln('      app_store_connect:')
        ..writeln('        auth: integration')
        ..writeln('        submit_to_testflight: true')
        ..writeln('        submit_to_app_store: false');
    } else {
      b.writeln(
        '      # app_store_connect: add an App Store Connect API key under Credentials',
      );
    }
    b
      ..writeln('      email:')
      ..writeln('        recipients:')
      ..writeln('          - team@example.com')
      ..writeln();
    return b.toString();
  }
}
