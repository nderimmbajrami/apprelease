/// What kind of project the repository holds.
enum ProjectType {
  flutter,
  reactNative;

  String get label => switch (this) {
    ProjectType.flutter => 'Flutter',
    ProjectType.reactNative => 'React Native',
  };
}

/// A store the app ships to.
enum Platform {
  android,
  ios;

  String get label => switch (this) {
    Platform.android => 'Android',
    Platform.ios => 'iOS',
  };
}

/// One "push to this branch, release there" rule. A branch ending in `*`
/// matches every branch with that prefix (`release/*`).
class PushRule {
  const PushRule({
    required this.branch,
    this.platforms = const {Platform.android},
    this.trackAndroid = 'internal',
    this.trackIos = 'testflight',
  });

  final String branch;
  final Set<Platform> platforms;

  /// `internal`, `alpha`, `beta` or `production`.
  final String trackAndroid;

  /// `testflight` or `appStore`.
  final String trackIos;

  PushRule copyWith({
    String? branch,
    Set<Platform>? platforms,
    String? trackAndroid,
    String? trackIos,
  }) => PushRule(
    branch: branch ?? this.branch,
    platforms: platforms ?? this.platforms,
    trackAndroid: trackAndroid ?? this.trackAndroid,
    trackIos: trackIos ?? this.trackIos,
  );

  Map<String, dynamic> toJson() => {
    'branch': branch,
    'platforms': [for (final p in platforms) p.name],
    'track_android': trackAndroid,
    'track_ios': trackIos,
  };

  static PushRule fromJson(Map json) => PushRule(
    branch: (json['branch'] as String?) ?? 'main',
    platforms: {
      for (final p in (json['platforms'] as List?) ?? const ['android'])
        if (Platform.values.any((x) => x.name == p))
          Platform.values.byName('$p'),
    },
    trackAndroid: (json['track_android'] as String?) ?? 'internal',
    trackIos: (json['track_ios'] as String?) ?? 'testflight',
  );

  /// The usual pair: a development branch to testers, main to the stores.
  static const defaults = [
    PushRule(branch: 'develop', platforms: {Platform.android, Platform.ios}),
    PushRule(
      branch: 'main',
      platforms: {Platform.android, Platform.ios},
      trackAndroid: 'production',
      trackIos: 'appStore',
    ),
  ];
}

/// An application registered on AppRelease: the repository and what to build
/// from it. Credentials and releases hang off it by id.
class AppProject {
  const AppProject({
    required this.id,
    required this.teamId,
    required this.name,
    required this.repoUrl,
    required this.createdAt,
    this.branch = 'main',
    this.projectType = ProjectType.flutter,
    this.platforms = const {Platform.android, Platform.ios},
    this.androidPackageName = '',
    this.iosBundleId = '',
    this.flutterVersion = 'stable',
    this.releaseCount = 0,
    this.lastReleaseAt,
    this.triggerEnabled = false,
    this.pushRules = const [PushRule(branch: 'main')],
    this.triggerTags = false,
    this.webhookSecret = '',
  });

  final String id;
  final String teamId;
  final String name;
  final String repoUrl;
  final String branch;
  final ProjectType projectType;
  final Set<Platform> platforms;

  /// `com.example.app` — needed to read the build number from Google Play.
  final String androidPackageName;

  /// `com.example.app` — needed for automatic iOS signing.
  final String iosBundleId;

  /// `stable`, `beta`, `master`, a version, or `fvm`.
  final String flutterVersion;

  final DateTime createdAt;

  /// Denormalised for the list; the releases table is the truth.
  final int releaseCount;
  final DateTime? lastReleaseAt;

  /// Push triggers: GitHub posts to the webhook, a release is queued.
  final bool triggerEnabled;

  /// Which branch goes where. The first rule that names a platform for a
  /// pushed branch decides that platform's track.
  final List<PushRule> pushRules;

  /// A tag like `v1.4.0` releases to production / App Store review.
  final bool triggerTags;

  /// Signs GitHub's deliveries. Generated by the backend; empty locally.
  final String webhookSecret;

  bool get hasAndroid => platforms.contains(Platform.android);
  bool get hasIos => platforms.contains(Platform.ios);

  /// `acme/app` out of `https://github.com/acme/app.git`.
  String get repoShortName {
    final cleaned = repoUrl.replaceAll(RegExp(r'\.git/?$'), '');
    final parts = cleaned.split(RegExp(r'[/:]')).where((p) => p.isNotEmpty);
    final list = parts.toList();
    if (list.length < 2) return cleaned;
    return '${list[list.length - 2]}/${list.last}';
  }

  /// A url-ish id for the yaml workflow names: "acme-app".
  String get slug => name
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9]+'), '-')
      .replaceAll(RegExp(r'^-|-$'), '');

  AppProject copyWith({
    String? name,
    String? repoUrl,
    String? branch,
    ProjectType? projectType,
    Set<Platform>? platforms,
    String? androidPackageName,
    String? iosBundleId,
    String? flutterVersion,
    int? releaseCount,
    DateTime? lastReleaseAt,
    bool? triggerEnabled,
    List<PushRule>? pushRules,
    bool? triggerTags,
    String? webhookSecret,
  }) => AppProject(
    id: id,
    teamId: teamId,
    name: name ?? this.name,
    repoUrl: repoUrl ?? this.repoUrl,
    branch: branch ?? this.branch,
    projectType: projectType ?? this.projectType,
    platforms: platforms ?? this.platforms,
    androidPackageName: androidPackageName ?? this.androidPackageName,
    iosBundleId: iosBundleId ?? this.iosBundleId,
    flutterVersion: flutterVersion ?? this.flutterVersion,
    createdAt: createdAt,
    releaseCount: releaseCount ?? this.releaseCount,
    lastReleaseAt: lastReleaseAt ?? this.lastReleaseAt,
    triggerEnabled: triggerEnabled ?? this.triggerEnabled,
    pushRules: pushRules ?? this.pushRules,
    triggerTags: triggerTags ?? this.triggerTags,
    webhookSecret: webhookSecret ?? this.webhookSecret,
  );
}
