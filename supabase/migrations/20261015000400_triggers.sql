-- Push triggers: GitHub tells us about a push, we queue a release.
alter table public.apps
  add column if not exists trigger_enabled        boolean not null default false,
  add column if not exists trigger_branch         text    not null default 'main',
  add column if not exists trigger_platforms      text[]  not null default '{android}',
  add column if not exists trigger_track_android  text    not null default 'internal',
  add column if not exists trigger_track_ios      text    not null default 'testflight',
  add column if not exists trigger_tags           boolean not null default false,
  -- Shared with GitHub once; signs every delivery. Generated by the console.
  add column if not exists webhook_secret         text    not null default encode(extensions.gen_random_bytes(24), 'hex');

-- The next release number for an app, used by the webhook function.
create or replace function public.next_release_number(p_app_id uuid)
returns integer
language sql stable security definer set search_path = public
as $$
  select coalesce(max(number), 0) + 1 from public.releases where app_id = p_app_id
$$;
